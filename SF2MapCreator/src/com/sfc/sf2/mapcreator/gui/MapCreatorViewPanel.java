    protected void jCheckBoxPriorityItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCheckBoxPriorityItemStateChanged
        if (!ActionManager.isActionTriggering()) {
            ActionManager.setActionWithoutExecute(new ToggleAction(jCheckBoxPriority, jCheckBoxPriority.isSelected()));
        }
        if (layoutPanel != null) {
            layoutPanel.setShowPriority(jCheckBoxPriority.isSelected());
        }
    }//GEN-LAST:event_jCheckBoxPriorityItemStateChanged

    protected void jCheckBoxMapFlagsItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCheckBoxMapFlagsItemStateChanged
        if (!ActionManager.isActionTriggering()) {
            ActionManager.setActionWithoutExecute(new ToggleAction(jCheckBoxMapFlags, jCheckBoxMapFlags.isSelected()));
        }
        if (layoutPanel != null) {
            layoutPanel.setShowExplorationFlags(jCheckBoxMapFlags.isSelected());
            layoutPanel.setShowInteractionFlags(jCheckBoxMapFlags.isSelected());
        }
    }//GEN-LAST:event_jCheckBoxMapFlagsItemStateChanged

    private void jCheckBoxAddedTilesItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCheckBoxAddedTilesItemStateChanged
        if (!ActionManager.isActionTriggering()) {
            ActionManager.setActionWithoutExecute(new ToggleAction(jCheckBoxAddedTiles, jCheckBoxAddedTiles.isSelected()));
        }
        MapCreatorLayoutPanel panel = (MapCreatorLayoutPanel)layoutPanel;
        if (panel != null) {
            panel.setShowAddedTiles(jCheckBoxAddedTiles.isSelected());
        }
    }//GEN-LAST:event_jCheckBoxAddedTilesItemStateChanged

    private void jCheckBoxOrphanTilesItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jCheckBoxOrphanTilesItemStateChanged
        if (!ActionManager.isActionTriggering()) {
            ActionManager.setActionWithoutExecute(new ToggleAction(jCheckBoxOrphanTiles, jCheckBoxOrphanTiles.isSelected()));
        }
        MapCreatorLayoutPanel panel = (MapCreatorLayoutPanel)layoutPanel;
        if (panel != null) {
            panel.setShowOrphanTiles(jCheckBoxOrphanTiles.isSelected());
        }
    }//GEN-LAST:event_jCheckBoxOrphanTilesItemStateChanged

